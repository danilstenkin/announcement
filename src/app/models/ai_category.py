from enum import Enum


class AiCategoryEnum(str, Enum):
    """Тематическая категория анонса, определяемая ИИ по содержанию письма.

    Отдельная от AnnouncementCategoryEnum (тот отражает жизненный цикл:
    NEW/CHANGE/REVOKED и уходит в ивенты). Здесь — тема сообщения.
    Значения хранятся как русские метки (идут в UI как есть).
    """

    CHANGE = "Изменения"          # новые/изменённые продукты, услуги, условия, акции, графики
    INCIDENT = "Инциденты"        # сбои, аварии, недоступность систем, критические ошибки
    QUALITY = "Качество работы"   # напоминания, разъяснения, справочная информация


# Правила категоризации для ИИ (кладём в description поля category json-схемы).
AI_CATEGORY_RULES = (
    "Определи тематическую категорию анонса по содержанию письма. Верни ровно одно значение.\n"
    "ГЛАВНОЕ ПРАВИЛО (при сомнении между «Изменения» и «Инциденты»): если есть недоступность "
    "систем/сервисов, простой или влияние на обслуживание клиентов, либо любые технические работы "
    "(в т.ч. ПЛАНОВЫЕ) — это «Инциденты», даже если работы называются плановыми или временными.\n"
    "- «Инциденты» — массовые сбои сервисов, аварийные ситуации, недоступность систем, "
    "критические ошибки; любые технические/плановые работы с временной недоступностью сервисов или "
    "влиянием на обслуживание клиентов (например: плановые работы на системе, замена сертификата, "
    "обновление ПО с простоем, техработы с окном недоступности); иные инциденты высокого приоритета.\n"
    "- «Изменения» — запуск новых продуктов/услуг/функционала, изменение условий продуктов и "
    "сервисов, акции, изменение графика работы ОТДЕЛЕНИЙ/сотрудников, актуализация ранее "
    "опубликованной информации. Только когда НЕТ простоя клиентских сервисов и техработ.\n"
    "- «Качество работы» — напоминания, разъяснения и рекомендации, справочная информация, "
    "информационные уведомления."
)
