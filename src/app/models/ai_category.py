from enum import Enum


class AiCategoryEnum(str, Enum):
    """Тематическая категория анонса, определяемая ИИ по содержанию письма.

    Отдельная от AnnouncementCategoryEnum (тот отражает жизненный цикл:
    NEW/CHANGE/REVOKED и уходит в ивенты). Здесь — тема сообщения.
    Значения хранятся как русские метки (идут в UI как есть).
    """

    CHANGE = "Изменения"          # новые/изменённые продукты, услуги, условия, акции, графики
    INCIDENT = "Инциденты"        # сбои, аварии, недоступность систем, критические ошибки
    QUALITY = "Качество работы"   # напоминания, разъяснения, справочная информация


# Правила категоризации для ИИ (кладём в description поля category json-схемы).
